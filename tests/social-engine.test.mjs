test('expired tokens are fenced, retries are bounded and paused workers cannot claim',async()=>{
 await actor('steve');await cmd('run',{role:'analytics',requestId:'70000000-0000-4000-8000-000000000003'});
 await release();const old=await rpc('hub_social_claim');assert.ok(old);
 await db.exec("reset role;update social_tasks set lease_until=now()-interval '1 second' where state='running'");
 await worker();assert.equal(await rpc('hub_social_claim'),null);assert.equal((await execute(old)).stale,true);
 await db.exec("reset role;update social_tasks set available_at=now() where state='retry'");
 await release();const fresh=await rpc('hub_social_claim');assert.notEqual(fresh.token,old.token);assert.equal((await execute(old)).stale,true);
 assert.equal((await execute(fresh)).errorCode,'analytics_adapter_unconfigured');
 await actor('steve');await cmd('pause',{role:'scout'});await cmd('run',{role:'scout',requestId:'70000000-0000-4000-8000-000000000004'});
 await release();assert.equal(await rpc('hub_social_claim'),null);
});
test('worker drain is bounded, stops on transport failure and never invents success',async()=>{
 let count=0;const store={tick:async()=>{},claim:async()=>({id:'job'}),execute:async()=>{count++;}};
 assert.equal((await drain(store,()=>0)).processed,8);assert.equal(count,8);
 await assert.rejects(drain({...store,execute:async()=>{throw Error('transport');}}),/transport/);
 assert.equal(command.safeParse({action:'run',role:'scout',requestId:'bad'}).success,false);
});
